import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const base=pathToFileURL(resolve('research/semantic-quotient/state-identity-unification/src')+'/');
const {createSlot64ResidualQuotientKernel}=await import(new URL('quotient-native-negamax-slot64-residual-kernel.mjs',base));
const {createSemanticSharedTtArena}=await import(new URL('quotient-semantic-shared-tt.mjs',base));
const {createOnlineDependencyCoordinator}=await import(new URL('quotient-online-dependency-coordinator.mjs',base));
const spec={columns:7,rows:6,connect:4};
const {kernel}=createSlot64ResidualQuotientKernel(spec,{cacheEdges:false,prefixClasses:4096});
const arena=createSemanticSharedTtArena({entryCapacity:4096,termCapacity:1048576,domainSpec:spec});
const pending=[];
const executor={submit(message,priority){return new Promise((resolve,reject)=>pending.push({message,priority,reject}));}};
const coordinator=createOnlineDependencyCoordinator(kernel,arena,executor,{splitDepth:3,priorityProbeDepth:0});
const stopped=new Error('bounded diagnostic stops before executing the first leaf proof');
const task=coordinator.engine.search(kernel.rootId,0,1).then(()=>{throw Error('unexpected root completion');},error=>assert.equal(error,stopped));
await new Promise(resolve=>setImmediate(resolve));
assert.equal(pending.length,1);
const result={kind:'standard7x6-initial-proof-supply-diagnostic',sourceRevision:'9c778bcaf010372ca2a3a91a7cdcec8debf5518f',splitDepth:3,priorityProbeDepth:0,explorationEnabled:false,submittedAuthoritativeTasks:pending.map(({message,priority})=>({message,priority})),coordinator:coordinator.stats(),metrics:{...coordinator.engine.metrics},scope:'bounded initial dependency expansion only; no leaf proof or root solve executed',outcome:'exactly one initial authoritative task; other workers cannot receive authoritative siblings until a preferred-child result'};
for(const entry of pending) entry.reject(stopped);
await task;
await coordinator.engine.drainBackground();
fs.writeFileSync('../frontier-audit-results/local-method-review-initial-supply.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
