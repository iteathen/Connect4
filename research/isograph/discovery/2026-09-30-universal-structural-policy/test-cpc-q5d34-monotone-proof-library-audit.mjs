import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';

const dir=dirname(fileURLToPath(import.meta.url));
const script=resolve(dir,'run-cpc-q5d34-monotone-proof-library-audit.mjs');
const library=process.argv[2];assert(library);
const raw=execFileSync(process.execPath,[script,library],{encoding:'utf8',maxBuffer:64*1024*1024});
const r=JSON.parse(raw);

assert.equal(r.schema,'connect4.cpc_q5d34_monotone_proof_library_audit.v1');
assert.equal(r.jsMinSysSha,'bf23d3a67652cd42e1975f29c7dc4eed54f7eb42');
assert.equal(r.exactQClass,'5d34e24395b9d801');
assert.equal(r.sequence,'4444415666662322224255115153113777');
assert.equal(r.rank,34);
assert.deepEqual(r.support,[6,6,3,6,5,5,3]);
assert.equal(r.mover,'P0');
assert.deepEqual(r.terminalSafeP0Columns,[5,6,7]);
assert.ok(Array.isArray(r.positiveCertificates));
assert.ok(Array.isArray(r.routeAttempts));
assert.ok(Array.isArray(r.legacyTargetFamilies));
assert.deepEqual(r.legacyTargetEngineKinds,['LAMBDA','THETA','DISTANCE2_TARGET_SUPPORT','DISTANCE1_RESOLVED_TAIL_CAPACITY']);
assert.ok(Number.isInteger(r.summary.legacyTargetResourceFailureCount));
assert.ok(['P0_WIN','P0_LOSS','UNKNOWN'].includes(r.disposition));
assert.equal(typeof r.lossCertificate,'object');
assert.equal(typeof r.lossCertificate.loss,'boolean');
if(r.disposition==='P0_WIN')assert.ok(r.positiveCertificates.length>0);
if(r.disposition==='P0_LOSS'){assert.equal(r.positiveCertificates.length,0);assert.equal(r.lossCertificate.loss,true);}
if(r.positiveCertificates.length>0)assert.equal(r.lossCertificate.loss,false);
assert.equal(r.summary.resourceFailureCount,0);
assert.equal(r.oracleUsed,false);
assert.equal(r.solvedInputsUsed,false);
assert.equal(r.ordinaryFreeBranchGameTreeUsed,false);
assert.equal(r.productionCpcModified,false);
assert.equal(r.jsMinSysModified,false);
assert.equal(r.legacyRepairModified,false);
assert.equal(r.rcicModified,false);
assert.equal(r.forcedLossModified,false);
assert.equal(r.bsfpModified,false);
console.log(JSON.stringify({pass:true,disposition:r.disposition,positive:r.positiveCertificates.map(x=>x.kind),loss:r.lossCertificate.loss,summary:r.summary}));
